void SSC_Reset(SuperSerialCard* pSSC) {
  pSSC->m_vRecvBytes = 0;
  pSSC->m_bTxIrqEnabled = false;
  pSSC->m_bRxIrqEnabled = false;
  pSSC->m_bWrittenTx = false;
  pSSC->m_vbCommIRQ = false;
  pSSC->m_uCommandByte = 0xFF;
}

